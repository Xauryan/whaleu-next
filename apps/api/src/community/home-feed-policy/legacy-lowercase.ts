function contains(
  ranges: readonly (readonly [number, number])[],
  codepoint: number,
): boolean {
  let lo = 0;
  let hi = ranges.length - 1;
  while (lo <= hi) {
    const middle = (lo + hi) >>> 1;
    const [start, end] = ranges[middle]!;
    if (codepoint < start) hi = middle - 1;
    else if (codepoint > end) lo = middle + 1;
    else return true;
  }
  return false;
}
const isCased = (codepoint: number): boolean =>
  contains(casedRanges, codepoint);
const isIgnorable = (codepoint: number): boolean =>
  contains(ignorableRanges, codepoint);

export function legacyHomeLowercase(text: string): string {
  const input = Array.from(text, (character) => character.codePointAt(0)!);
  const buffer: number[] = [];
  const result: string[] = [];
  let previousEnd = 0;
  const scanAhead = (start: number): boolean => {
    for (let index = start; index < input.length; index++) {
      if (isCased(input[index]!)) return true;
      if (!isIgnorable(input[index]!)) return false;
    }
    return false;
  };
  for (let offset = 0; offset < input.length; offset += 64) {
    const chunk = input.slice(offset, offset + 64);
    let position = 0;
    for (let index = 0; index < chunk.length; index++) {
      const codepoint = chunk[index]!;
      let finalSigma = false;
      if (codepoint === 0x3a3) {
        let cursor = index - 1;
        while (cursor >= 0 && isIgnorable(chunk[cursor]!)) cursor--;
        let preceding = false;
        if (cursor >= 0) preceding = isCased(chunk[cursor]!);
        else {
          // Retain only the previous converted buffer tail not yet overwritten
          // by this chunk. PHP's boundary helper checks Cased before Ignorable.
          for (
            let previous = previousEnd - 1;
            previous >= position;
            previous--
          ) {
            if (isCased(buffer[previous]!)) {
              preceding = true;
              break;
            }
            if (!isIgnorable(buffer[previous]!)) break;
          }
        }
        if (preceding) {
          cursor = index + 1;
          while (cursor < chunk.length && isIgnorable(chunk[cursor]!)) cursor++;
          finalSigma =
            cursor < chunk.length
              ? !isCased(chunk[cursor]!)
              : !scanAhead(offset + chunk.length);
        }
      }
      const mapped = finalSigma
        ? 'ς'
        : (mapping.get(codepoint) ?? String.fromCodePoint(codepoint));
      for (const character of mapped)
        buffer[position++] = character.codePointAt(0)!;
    }
    previousEnd = position;
    for (let index = 0; index < position; index++)
      result.push(String.fromCodePoint(buffer[index]!));
  }
  return result.join('');
}
